def template_group(body: str) -> str:
    m = TEMPLATE.search(body or "")
    if m:
        return m.group(1)
    return "issue_reporter" if "generated by issue reporter" in (body or "") else "none"


def analyse(issues: dict) -> dict:
    out = {}
    # Type: scores by the issue template recorded in the body.
    T = read("type_test_predictions.json")
    groups = defaultdict(list)
    for r in T:
        groups[template_group(issues[r["number"]]["body"])].append(r)
    out["type_by_template"] = {}
    for g, rs in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        t = [r["truth"] for r in rs]
        out["type_by_template"][g] = {
            "n": len(rs), "bug_share": sum(x == "bug" for x in t) / len(t),
            "feature_request_share": sum(x == "feature-request" for x in t) / len(t),
            **{m: {"accuracy": float(np.mean([r[m] == r["truth"] for r in rs])),
                   "macro_f1": float(f1_score(t, [r[m] for r in rs], average="macro", zero_division=0))}
               for m in TYPE_NAMES}}
    conf = Counter((r["truth"], r["logreg_accuracy"]) for r in T)
    out["type_accuracy_model_bug_feature_confusion"] = {
        "bug_predicted_as_feature_request": conf["bug", "feature-request"],
        "feature_request_predicted_as_bug": conf["feature-request", "bug"]}

    # Module: per-module hit rates and the most frequent first guesses for weak modules.
    M = read("module_test_predictions.json")
    cnt, h1, h3 = Counter(), Counter(), Counter()
    for r in M:
        for m in r["truth"]:
            cnt[m] += 1
            h1[m] += r["logreg_top1_hit"]
            h3[m] += r["logreg_top3_hit"]
    per = {m: {"test_issues": cnt[m], "top1": h1[m] / cnt[m], "top3": h3[m] / cnt[m]} for m in cnt}
    out["module_per_module_min15"] = dict(sorted(((m, v) for m, v in per.items() if v["test_issues"] >= 15),
                                                 key=lambda kv: kv[1]["top1"]))
    out["module_first_guess_for_terminal"] = dict(Counter(
        r["logreg_top3"][0] for r in M if "terminal" in r["truth"]).most_common(5))
    train_mods = Counter(m for x in load_sets("module")["train"] for m in x["truth"])
    out["module_terminal_family_in_train"] = {
        "labels": sum(1 for m in train_mods if "terminal" in m),
        "terminal": train_mods["terminal"], "chat-terminal": train_mods["chat-terminal"]}
    out["module_top3_misses"] = sum(1 for r in M if not r["logreg_top3_hit"])

    # Duplicate: which method finds the original in its top 10, and how often texts exceed 512 tokens.
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(MODEL_ID, revision=MODEL_REVISION)
    long = lambda n: len(tok(issue_text(issues[n]), truncation=False, verbose=False)["input_ids"]) > 512
    D = read("duplicate_test_predictions.json")
    dup = {}
    for r in D:
        b, e = r["bm25_rank"] <= 10, r["embedding_rank"] <= 10
        g = "both" if b and e else "bm25_only" if b else "embedding_only" if e else "neither"
        d = dup.setdefault(g, {"n": 0, "query_or_original_over_512_tokens": 0})
        d["n"] += 1
        d["query_or_original_over_512_tokens"] += int(long(r["query"]) or long(r["original"]))
    out["duplicate_top10_overlap"] = {g: dup[g] for g in ("both", "bm25_only", "embedding_only", "neither")}
    return out


