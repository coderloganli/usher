def read(name: str) -> dict:
    with open(OUT / name, encoding="utf-8") as f:
        return json.load(f)


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def pp(x: float) -> str:
    return f"{100 * x:+.1f}"


def ci_pct(s: dict) -> str:
    return f"{pct(s['point'])} <span class='muted'>({100 * s['ci95'][0]:.1f}–{100 * s['ci95'][1]:.1f}%)</span>"


def ci_f1(s: dict) -> str:
    return f"{s['point']:.3f} <span class='muted'>({s['ci95'][0]:.3f}–{s['ci95'][1]:.3f})</span>"


def diff_pp(d: dict) -> str:
    sig = "yes" if d["excludes_zero"] else "no"
    return f"{pp(d['point'])} points <span class='muted'>({pp(d['ci95'][0])} to {pp(d['ci95'][1])})</span></td><td>{sig}"


def diff_f1(d: dict) -> str:
    sig = "yes" if d["excludes_zero"] else "no"
    return f"{d['point']:+.3f} <span class='muted'>({d['ci95'][0]:+.3f} to {d['ci95'][1]:+.3f})</span></td><td>{sig}"


def table(head: list[str], rows: list[list[str]], num_cols: set[int] = frozenset()) -> str:
    th = "".join(f"<th{' class=num' if i in num_cols else ''}>{h}</th>" for i, h in enumerate(head))
    body = "".join("<tr>" + "".join(f"<td{' class=num' if i in num_cols else ''}>{c}</td>" for i, c in enumerate(r))
                   + "</tr>" for r in rows)
    return f"<div class='scroll'><table><tr>{th}</tr>{body}</table></div>"


